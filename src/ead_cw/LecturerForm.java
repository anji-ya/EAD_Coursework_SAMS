    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        try {
    // 1. Connect to the 'sams' database
    java.sql.Connection con = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/sams", "root", "");

    // 2. Prepare the SQL Update Statement
    // We update name, email, and department WHERE the lecturer_id matches
    String sql = "UPDATE lecturers SET name = ?, email = ?, department = ? WHERE lecturer_id = ?";
    java.sql.PreparedStatement pst = con.prepareStatement(sql);
    
    // 3. Set the values from your TextFields
    pst.setString(1, txtLecturerName.getText());
    pst.setString(2, txtLecturerEmail.getText());
    pst.setString(3, txtDept.getText());
    pst.setString(4, txtLecturerID.getText()); // This matches the 'WHERE' clause

    // 4. Execute the update
    int rowsUpdated = pst.executeUpdate();
    
    if (rowsUpdated > 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Lecturer Record Updated Successfully!");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "No lecturer found with that ID.");
    }
    
    con.close();
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Update Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        // 1. Ask the user for confirmation before deleting
int dialogResult = javax.swing.JOptionPane.showConfirmDialog(this, 
    "Are you sure you want to delete this lecturer?", "Warning", javax.swing.JOptionPane.YES_NO_OPTION);

if (dialogResult == javax.swing.JOptionPane.YES_OPTION) {
    try {
        // 2. Connect to the 'sams' database
        java.sql.Connection con = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/sams", "root", "");

        // 3. Prepare the SQL Delete Statement
        String sql = "DELETE FROM lecturers WHERE lecturer_id = ?";
        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        
        // Use the ID from the text box to identify who to delete
        pst.setString(1, txtLecturerID.getText());

        // 4. Execute
        int rowsDeleted = pst.executeUpdate();
        
        if (rowsDeleted > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Lecturer Deleted Successfully!");
            
            // 5. Clear the text boxes after deleting
            txtLecturerID.setText("");
            txtLecturerName.setText("");
            txtLecturerEmail.setText("");
            txtDept.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Lecturer ID not found.");
        }
        
        con.close();
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Delete Error: " + e.getMessage());
    }
}
    }//GEN-LAST:event_btnDeleteActionPerformed

