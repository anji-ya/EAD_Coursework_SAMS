    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        try {
    // 1. Get the data from your specific Lecturer fields
    String id = txtLecturerID.getText();
    String name = txtLecturerName.getText();
    String email = txtLecturerEmail.getText();
    String dept = txtDept.getText();

    // 2. Connect to the 'sams' database
    java.sql.Connection con = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/sams", "root", "");

    // 3. Prepare SQL (Make sure you ran the CREATE TABLE command in phpMyAdmin first!)
    String sql = "INSERT INTO lecturers (lecturer_id, name, email, department) VALUES (?, ?, ?, ?)";
    java.sql.PreparedStatement pst = con.prepareStatement(sql);
    
    pst.setString(1, id);
    pst.setString(2, name);
    pst.setString(3, email);
    pst.setString(4, dept);

    // 4. Execute and show success
    pst.executeUpdate();
    javax.swing.JOptionPane.showMessageDialog(this, "Lecturer Added Successfully!");
    
    con.close();
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

