    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                        
    // 1. Validation: Check if fields are empty first
    if (txtID.getText().isEmpty() || txtName.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Student ID and Name cannot be empty!", "Validation Error", JOptionPane.ERROR_MESSAGE);
        
        JOptionPane.showMessageDialog(this, "Please fill in all required fields!");
    return;// Stops the code here if empty
    }

    try {
        // 2. Get data from your TextFields and Combo Box
        String id = txtID.getText();
        String name = txtName.getText();
        String email = txtEmail.getText();
        String course = cmbCourse.getSelectedItem().toString(); // This will be SE, DS, CS, or IS

        // 3. Database Connection (Using your DBConnection class)
        Connection conn = DBConnection.connect();

        // 4. Prepare the SQL Statement
        String sql = "INSERT INTO students (student_id, name, email, course_id) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(sql);
        
        pst.setString(1, id);
        pst.setString(2, name);
        pst.setString(3, email);
        pst.setString(4, course);

        // 5. Run the update
        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "Student Registered Successfully!");

        // Optional: Clear fields after success
        btnClearActionPerformed(null);

    } catch (Exception e) {
        // This will catch the "Foreign Key" error if you haven't added SE/DS to the courses table yet
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
    
}
    
    }//GEN-LAST:event_jButton1ActionPerformed

