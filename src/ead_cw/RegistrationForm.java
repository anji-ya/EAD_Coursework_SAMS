    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
// Change this line in your Update button:
    // TODO add your handling code here:
        try {
    Connection conn = DBConnection.connect();
    // We find the student by ID and update the other 3 fields
    String sql = "UPDATE students SET name = ?, email = ?, course_id = ? WHERE student_id = ?";
    PreparedStatement pst = conn.prepareStatement(sql);
    
    // The order here must match the '?' marks in the SQL string above
    pst.setString(1, txtName.getText());
    pst.setString(2, txtEmail.getText());
    // Change this line in your Update button:
pst.setString(3, cmbCourse.getSelectedItem().toString()); // Set the course
pst.setString(4, txtID.getText()); // Set the ID for the WHERE clause
    int rowsUpdated = pst.executeUpdate();
    
    if (rowsUpdated > 0) {
        JOptionPane.showMessageDialog(this, "Student Record Updated Successfully!");
    } else {
        JOptionPane.showMessageDialog(this, "No record found with that ID to update.");
    }
    
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Update Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

